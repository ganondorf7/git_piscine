int ft_find_next_prime(int nb)
{
	int	i;

	if (nb <= 1)
		return(2);
	nb++;
	while (nb < 2147483647)
	{
		i = 2;
		while (i * i <= nb)
			{
				if (nb % i == 0)
					break;
				i++;
			}
		if (i * i > nb)
			return (nb);
		nb++;
	}
	return(0);
}
